interface I18nContextType {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: string, fallback?: string) => string;
}

const I18nContext = createContext<I18nContextType | null>(null);

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>(() => {
    const saved = localStorage.getItem('aigov_lang') as Lang;
    return saved && translations[saved] ? saved : 'ko';
  });

  const setLang = useCallback((newLang: Lang) => {
    localStorage.setItem('aigov_lang', newLang);
    setLangState(newLang);
    document.documentElement.lang = newLang === 'zh' ? 'zh-CN' : newLang;
  }, []);

  const t = useCallback((key: string, fallback?: string): string => {
    return translations[lang]?.[key] || translations['ko']?.[key] || fallback || key;
  }, [lang]);

  return (
    <I18nContext.Provider value={{ lang, setLang, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used within I18nProvider');
  return ctx;
}
